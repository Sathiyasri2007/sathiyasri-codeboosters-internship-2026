"""# ETL Pipeline

ETL stands for Extract, Transform, and Load.

Extract:
- Read data from source files.

Transform:
- Clean and prepare the data.

Load:
- Save the processed data for further analysis.
"""

import pandas as pd

# Extract
def extract():
    print("Extracting data...")
    return pd.read_csv("cleaned_telco_churn.csv")

# Transform
def transform(df):
    print("Transforming data...")

    df["Customer_Status"] = df["Tenure Months"].apply(
        lambda x: "Loyal" if x >= 24 else "New"
    )

    return df

# Load
def load(df):
    print("Loading data...")

    df.to_csv(
        "etl_output.csv",
        index=False
    )

# Execute ETL

data = extract()

data = transform(data)

load(data)

print("ETL Pipeline Completed Successfully!")

